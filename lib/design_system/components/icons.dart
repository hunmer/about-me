/// 图标组件：基于系统 Material Icons
class DsIcon extends StatelessWidget {
  const DsIcon(
    this.kind, {
    super.key,
    this.size = 24,
    this.color,
    this.fill = false,
  });

  final DsIconKind kind;
  final double size;
  final Color? color;
  final bool fill;

  @override
  Widget build(BuildContext context) {
    final theme = AppTheme.maybeOf(context);
    final effectiveColor = color ?? theme?.text ?? const Color(0xFF4C1D95);
    final data =
        kind == DsIconKind.heart && fill ? Icons.favorite : _kIcons[kind]!;
    // WiredIcon：已注册的手绘图标目录命中时画手绘几何，
    // 未收录的图标自动回退普通 Icon，风格与全局粗糙度一致
    return WiredIcon(
      icon: data,
      size: size,
      color: effectiveColor,
      drawConfig: theme?.wired.drawConfig,
    );
  }
}
