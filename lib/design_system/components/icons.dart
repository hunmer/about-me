/// 图标组件：基于系统 Material Icons
class DsIcon extends StatelessWidget {
  const DsIcon(
    this.kind, {
    super.key,
    this.size = 24,
    this.color,
    this.fill = false,
  });

  final DsIconKind kind;
  final double size;
  final Color? color;
  final bool fill;

  @override
  Widget build(BuildContext context) {
    final effectiveColor =
        color ?? AppTheme.maybeOf(context)?.text ?? const Color(0xFF4C1D95);
    final data =
        kind == DsIconKind.heart && fill ? Icons.favorite : _kIcons[kind]!;
    return Icon(data, size: size, color: effectiveColor);
  }
}
